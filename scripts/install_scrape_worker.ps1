# Installs the schoolngr question worker so it runs unattended in the background.
#
# Uses the user's Startup folder (no admin rights needed):
#   * starts the worker at every logon, with no console window
#   * restarts it automatically if it ever exits
#   * the worker itself keeps retrying while offline and resumes when the
#     connection returns
#
# Run once, from the repo root:
#   powershell -ExecutionPolicy Bypass -File scripts\install_scrape_worker.ps1
#
# Remove it again with:
#   powershell -ExecutionPolicy Bypass -File scripts\install_scrape_worker.ps1 -Uninstall

param(
    [switch]$Uninstall,
    [switch]$StartNow
)

$ErrorActionPreference = "Stop"
$RepoRoot = Split-Path -Parent $PSScriptRoot
$Worker = Join-Path $RepoRoot "scripts\scrape_worker.py"
$StartupDir = [Environment]::GetFolderPath("Startup")
$Launcher = Join-Path $StartupDir "JambCrashQuestionWorker.vbs"

if ($Uninstall) {
    if (Test-Path $Launcher) {
        Remove-Item $Launcher -Force
        Write-Host "Removed startup launcher."
    } else {
        Write-Host "No startup launcher installed."
    }
    Get-CimInstance Win32_Process -Filter "Name like 'python%'" -ErrorAction SilentlyContinue |
        Where-Object { $_.CommandLine -like "*scrape_worker.py*" } |
        ForEach-Object {
            Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue
            Write-Host "Stopped running worker (pid $($_.ProcessId))."
        }
    return
}

if (-not (Test-Path $Worker)) {
    throw "Worker not found at $Worker. Run this from the repo."
}

# Resolve the interpreter that `python` actually points at.
$python = $null
$probe = & python -c "import sys; print(sys.executable)" 2>$null
if ($LASTEXITCODE -eq 0 -and $probe -and (Test-Path $probe)) {
    $python = $probe.Trim()
}
if (-not $python) {
    throw "Python not found on PATH. Install Python 3 and try again."
}

# pythonw.exe runs without a console window; fall back to python.exe.
$pythonw = Join-Path (Split-Path -Parent $python) "pythonw.exe"
if (-not (Test-Path $pythonw)) { $pythonw = $python }

$vbs = @"
' Auto-generated by scripts\install_scrape_worker.ps1
' Keeps the JAMB past-question worker running in the background.
Set sh = CreateObject("WScript.Shell")
worker = "$Worker"
repo = "$RepoRoot"
pythonw = "$pythonw"
Do
    sh.CurrentDirectory = repo
    sh.Run """" & pythonw & """" & " " & """" & worker & """", 0, True
    WScript.Sleep 60000
Loop
"@

Set-Content -Path $Launcher -Value $vbs -Encoding ASCII
Write-Host "Installed startup launcher:"
Write-Host "  $Launcher"
Write-Host "  python : $pythonw"
Write-Host "  worker : $Worker"

if ($StartNow) {
    Start-Process -FilePath "wscript.exe" -ArgumentList "`"$Launcher`"" -WindowStyle Hidden
    Write-Host "Worker started now."
}

Write-Host ""
Write-Host "Check progress:  python scripts\scrape_worker.py --status"
Write-Host "Live log      :  Get-Content scripts\scrape-worker.log -Tail 30 -Wait"
Write-Host "Remove        :  powershell -ExecutionPolicy Bypass -File scripts\install_scrape_worker.ps1 -Uninstall"
